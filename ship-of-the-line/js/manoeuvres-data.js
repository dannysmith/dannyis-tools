//     haul, letGo, ease, show:   lists of [sailId, lineId, side?]. The ids are
//                         those of RIGDATA.SAILS. side is 'starboard',
//                         'larboard' or (when left out) both: the side of the
//                         ship the rope's yardarm or clew is on.
//     state }             the picture once the order has been carried out
//
// In this file each step's `state` gives only what changes; at the foot of
// the file every step is given the whole state, so readers of the data get
//
//   state: { wind, heading,      compass degrees; heading runs on past 360
//                                 or below 0 so that the turn has a direction
//            headName?,           the heading in words where it is not a whole point
//            yards: { fore, main, mizen, [sailId] },   degrees from square;
//                                 positive is the starboard yardarm forward,
//                                 the trim for the starboard tack
//            sails: { [sailId]: 'set' | 'hung' | 'in',
//                     jib, 'fore-topmast-staysail', staysails, 'mizen-staysail',
//                     mizen: 'starboard' | 'larboard' (the side its sheet is
//                     hauled) | 'flat' | 'fly' | 'in' },
//            force?: { [sailId]: 'becalmed' | 'shiver' | … }   this step only
//            rudder,              degrees; positive is the blade to starboard,
//                                 the tiller to larboard
//            way: 'ahead' | 'slow' | 'none' | 'astern' | 'anchor',
//            reefs?, anchor? }
//
