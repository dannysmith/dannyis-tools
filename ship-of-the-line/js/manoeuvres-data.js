//                         done when the sources give no words (spoken: false)
//     short?,             a shorter label for the list of orders
//     spoken?, from?,     from: whose words `order` is
//     variants: [{ words, who }],
//     text,               what is done (HTML)
//     helm, why?, also?,  also: gear that has no record in RIGDATA.SAILS
